#!/usr/bin/env python3
"""Build the published outputs from data/*.yaml.

Writes:
  dist/ai-search.csv, dist/ai-agents.csv     flat tables, one row per record
  dist/ai-search.json, dist/ai-agents.json   nested records with dataset metadata
  dist/landscape.json                        both datasets plus vocab labels (used by site/)
  STATS.md                                   counts by segment, country, region and founding year
  README.md                                  the block between the stats markers

Everything is derived from the YAML files, so the output is deterministic:
running the build twice gives byte-identical files.

Usage:
  python3 tools/build.py              write all outputs
  python3 tools/build.py --check      exit 1 if any output is out of date (used in CI)
  python3 tools/build.py --site DIR   also assemble the static site into DIR
"""

